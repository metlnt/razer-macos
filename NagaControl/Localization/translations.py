def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')

here = os.path.dirname(os.path.abspath(__file__))
keys = [row[0] for row in T]
assert len(keys) == len(set(keys)), "duplicate keys"
for i, lang in enumerate(["en"] + LANGS):
    d = os.path.join(here, f"{lang}.lproj")
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "Localizable.strings"), "w", encoding="utf-8") as f:
        f.write("/* Generated by translations.py — edit that file instead. */\n\n")
        for row in T:
            f.write(f'"{esc(row[0])}" = "{esc(row[i])}";\n')
print(f"{len(T)} strings × {len(LANGS) + 1} languages")
